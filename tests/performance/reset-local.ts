import { database } from "./environment";
import { Client } from "pg";
import { spawnSync } from "node:child_process";
import path from "node:path";

async function main() {
  // Destructive on purpose, but only with an explicit switch and hard-coded local targets.
  if (!process.argv.includes("--replace-synthetic-fixtures"))
    throw new Error(
      "Requires --local --replace-synthetic-fixtures. Replaces only Phase 21 synthetic test data.",
    );
  if (
    !["cinebite_phase21_test", "cinebite_phase21_baseline"].includes(database)
  )
    throw new Error("Unexpected test database.");
  const connection = { host: "127.0.0.1", port: 55414, user: "cinebite_test" };
  const fixture = new Client({ ...connection, database });
  await fixture.connect();
  try {
    const table = await fixture.query(
      "SELECT to_regclass('public.organizations') AS name",
    );
    if (table.rows[0].name) {
      const result = await fixture.query(
        "SELECT count(*)::int AS count FROM organizations WHERE slug NOT LIKE 'phase21-evidence-%'",
      );
      if (result.rows[0].count !== 0)
        throw new Error("Refusing to replace non-Phase-21 data.");
    }
  } finally {
    await fixture.end();
  }
  const admin = new Client({ ...connection, database: "postgres" });
  await admin.connect();
  try {
    // No FORCE: an active harness/server must be stopped first, never kill unrelated clients.
    await admin.query(`DROP DATABASE "${database}"`);
    await admin.query(`CREATE DATABASE "${database}" OWNER cinebite_test`);
  } finally {
    await admin.end();
  }
  const migration = spawnSync(
    process.execPath,
    [path.resolve("node_modules/prisma/build/index.js"), "migrate", "deploy"],
    { env: process.env, stdio: "inherit", windowsHide: true },
  );
  if (migration.status !== 0)
    throw new Error("Dedicated test migration failed.");
  const prepared = new Client({ ...connection, database });
  await prepared.connect();
  try {
    await prepared.query("CREATE EXTENSION IF NOT EXISTS pg_stat_statements");
  } finally {
    await prepared.end();
  }
  console.log(
    "Recreated only " +
      database +
      " on local port 55414; synthetic fixtures are regenerated by the harness.",
  );
}
main().catch((error) => {
  console.error(error instanceof Error ? error.message : "Local reset failed.");
  process.exitCode = 1;
});
